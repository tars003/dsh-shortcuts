import { readFile, mkdir, writeFile } from 'node:fs/promises';

// DSH's lazy factory format. No bundler or install-time script is needed.
// Keep lib/client.js in Git so installation from GitHub works without prepare.
const root = new URL('../', import.meta.url);
const parts = [];
for (const file of ['shortcuts', 'preferences', 'client']) {
  const source = await readFile(new URL(`src/${file}.js`, root), 'utf8');
  parts.push(source.replace(/^import .*;\n/gm, '').replace(/^export /gm, ''));
}
const bundle = `// Generated by npm run build; edit src/ instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-shortcuts',\n  factory: (require) => {\n    const React = require('react');\n${parts.join('\n')}\n    return { apply, inject };\n  },\n});\n`;
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), bundle);
console.log('Built lib/client.js');
